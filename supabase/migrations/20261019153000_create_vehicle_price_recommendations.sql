create table if not exists public.vehicle_price_recommendations (
  id bigint generated by default as identity primary key,
  car_id bigint not null references public.cars(id) on delete cascade,
  input_hash text not null,
  result jsonb not null,
  generated_at timestamptz not null default now(),
  expires_at timestamptz not null,
  created_by uuid not null default auth.uid() references auth.users(id) on delete cascade,
  constraint vehicle_price_recommendations_result_object_check
    check (jsonb_typeof(result) = 'object'),
  constraint vehicle_price_recommendations_expiry_check
    check (expires_at > generated_at)
);

create index if not exists vehicle_price_recommendations_cache_idx
  on public.vehicle_price_recommendations(created_by, car_id, input_hash, expires_at desc);

create index if not exists vehicle_price_recommendations_history_idx
  on public.vehicle_price_recommendations(created_by, car_id, generated_at desc);

alter table public.vehicle_price_recommendations enable row level security;

drop policy if exists "Users can select own vehicle price recommendations"
  on public.vehicle_price_recommendations;
drop policy if exists "Users can insert own vehicle price recommendations"
  on public.vehicle_price_recommendations;

create policy "Users can select own vehicle price recommendations"
on public.vehicle_price_recommendations for select to authenticated
using (created_by = auth.uid());

create policy "Users can insert own vehicle price recommendations"
on public.vehicle_price_recommendations for insert to authenticated
with check (created_by = auth.uid());

